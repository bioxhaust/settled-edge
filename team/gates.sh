#!/bin/sh
# ГЕЙТЫ — единственный источник истины о том, что значит «готово».
#
# Владелец: INTEGRATOR (team/CHARTER.md раздел 3).
# Запуск:   sh team/gates.sh          — все гейты
#           sh team/gates.sh fast     — только BUILD и TEST
#
# Выход 0 — все гейты зелёные. Любой другой — назови, какой упал, и не
# объявляй работу готовой.
#
# Ни один гейт здесь не подавляет предупреждение через #[allow]. Про
# xcrun_db-предупреждение линкера см. README.md: оно окружное, не про
# исходник, и исключается по тексту.
#
# Редакция decisions/029 (T1a). Что изменилось и почему — в конце файла,
# раздел «журнал правок измерителя». Три гейта краснели на собственной области
# поиска, а не на воркспейсе; правится область, правило не ослабляется ни в
# одном из трёх.

set -u
cd "$(dirname "$0")/.." || exit 2

PASS=0
FAIL=0
WARNS=0
RED=""

ok()   { printf '  \033[32mPASS\033[0m  %s\n' "$1"; PASS=$((PASS+1)); }
bad()  { printf '  \033[31mFAIL\033[0m  %s\n' "$1"; FAIL=$((FAIL+1)); RED="$RED $2"; }
warn() { printf '  \033[33mWARN\033[0m  %s\n' "$1"; WARNS=$((WARNS+1)); }

# Печатает попадания целиком по счёту и первые N по содержанию. `head` без
# объявленного остатка — способ спрятать находку: до этой правки NOUNWRAP
# показывал 10 попаданий из 221, и какие именно десять, зависело от порядка
# выдачи `find`. Настоящее нарушение на одиннадцатом месте не увидел бы никто.
show() {
  _n=$(printf '%s\n' "$1" | grep -c .)
  printf '%s\n' "$1" | head -"$2" | sed 's/^/        /'
  [ "$_n" -gt "$2" ] && printf '        … ещё %d, всего %d\n' "$((_n-$2))" "$_n"
  return 0
}

# ==================================================================
#  ГДЕ КОНЧАЕТСЯ ПРОДУКТОВЫЙ КОД
# ==================================================================
# Устав раздел 6: область NOUNWRAP и NOTLSDOWN — «вне `#[cfg(test)]`, и гейт
# может стоять в родителе» (редакция decisions/029 п.1 и п.2). Один
# классификатор на оба гейта, чтобы они не могли разойтись в том, где граница.
#
# Точная граница модулей шеллом не проводится — это признано и в decisions/029.
# Ниже названы оба допущения и то, чем каждое проверено на этом дереве, чтобы
# следующий читатель знал, где измеритель слепнет, а не догадывался.
#
# Допущение 1: `#[cfg(test)]` стоит на нулевой колонке.
#   Проверено: `grep -rn '^[[:space:]]\+#\[cfg(test)\]' crates/` пусто.
# Допущение 2: закрывающая скобка на нулевой колонке — настоящая структура, а не
#   символ внутри многострочного строкового литерала.
#   Проверено: в `crates/` три многострочных raw-литерала
#   (`arb-live/src/json.rs:789`, `:806`, `:835`), и ни в одном нет `}` на
#   нулевой колонке — все строки продолжения с отступом.
# Составных `#[cfg(all(test`/`any(test`, `#[path]` и блочных комментариев в
# дереве нет — проверено грепом; появятся — оба допущения надо пересчитать.

RS_ALL=$(find crates -name '*.rs' | sort)
RS_PROD=$(find crates -name '*.rs' -not -path '*/tests/*' | sort)

# Каталог, в котором лежат подмодули данного файла: рядом для `lib.rs`,
# `main.rs` и `mod.rs`, в одноимённом подкаталоге для всех прочих.
mod_dir() {
  case "$(basename "$1")" in
    lib.rs|main.rs|mod.rs) dirname "$1" ;;
    *) printf '%s' "${1%.rs}" ;;
  esac
}

# Объявления `mod x;` в файле. $2=0 — только те, над которыми стоит
# `#[cfg(test)]`; $2=1 — все (для замыкания внутри уже тестового модуля).
mod_decls() {
  awk -v D="$(mod_dir "$1")" -v ALL="$2" '
    /^[[:space:]]*#\[cfg\(test\)\]/ { gate=1; next }
    /^[[:space:]]*#\[/ { next }
    /^[[:space:]]*(pub[[:space:]]+)?mod[[:space:]]+[A-Za-z_][A-Za-z0-9_]*[[:space:]]*;/ {
      if (gate || ALL == "1") {
        n = $0
        sub(/^[[:space:]]*(pub[[:space:]]+)?mod[[:space:]]+/, "", n)
        sub(/[[:space:]]*;.*$/, "", n)
        print D "/" n ".rs"
        print D "/" n "/mod.rs"
      }
    }
    { gate = 0 }
  ' "$1"
}

# Модуль, объявленный как `#[cfg(test)] mod x;`, тестовый целиком, даже если
# внутри `x.rs` слова `#[cfg(test)]` нет. Так устроена `arb-adversary`
# (`decisions/010`), и корка, целиком состоящая из тестов, иначе красна по
# построению. Замыкание по вложенности: дети тестового модуля тоже тестовые.
TESTONLY=$(for f in $RS_ALL; do mod_decls "$f" 0; done | sort -u)
while :; do
  _grown=$(
    { printf '%s\n' "$TESTONLY"
      for f in $TESTONLY; do [ -f "$f" ] && mod_decls "$f" 1; done
    } | grep -v '^$' | sort -u
  )
  [ "$_grown" = "$TESTONLY" ] && break
  TESTONLY="$_grown"
done

# Строки продуктового кода в виде `путь:номер: текст`.
#
# Отбрасывается: тестовый файл целиком; область от `#[cfg(test)]` до
# закрывающей скобки на нулевой колонке; строчные комментарии, включая `///` и
# `//!` на отступе.
#
# Область закрывается, а не тянется до конца файла, как раньше. Прежняя
# эвристика ставила флаг на первом `#[cfg(test)]` и не снимала его никогда,
# поэтому продуктовый код *после* тестового модуля не проверялся вообще. Сейчас
# таких строк в дереве нет, но `crates/arb-live/src/venues/bybit.rs:566`
# (`pub mod captured`, намеренно вне `#[cfg(test)]`) стоит прямо над
# `#[cfg(test)] mod tests` — достаточно поменять два модуля местами, и он ушёл бы
# из поля зрения молча.
product_lines() {
  for f in $RS_PROD; do
    case "
$TESTONLY
" in *"
$f
"*) continue ;; esac
    awk -v F="$f" '
      /^#\[cfg\(test\)\]/ { pending = 1; next }
      pending && /^[[:space:]]*#\[/ { next }
      pending {
        pending = 0
        # Объявление без тела (`mod x;`) области не открывает: тестовая здесь
        # только сама строка. Без этой ветки восемь объявлений в
        # arb-adversary/src/lib.rs погасили бы весь остаток файла.
        if ($0 ~ /;[[:space:]]*$/ && $0 !~ /\{/) next
        skip = 1
        next
      }
      skip && /^\}/ { skip = 0; next }
      skip { next }
      {
        line = $0
        sub(/[[:space:]]*\/\/.*$/, "", line)
        if (line ~ /[^[:space:]]/) print F ":" NR ": " line
      }
    ' "$f"
  done
}

printf '\n=== ГЕЙТЫ ===\n\n'

# ---------------------------------------------------------------- BUILD
BUILD_LOG=$(cargo build --offline --workspace --message-format short 2>&1)
BUILD_RC=$?
# Отбрасываем окружный шум линкера, оставляем всё остальное.
BUILD_WARN=$(printf '%s\n' "$BUILD_LOG" \
  | grep -E '^(warning|error)' \
  | grep -v 'xcrun_db' \
  | grep -v "couldn't create cache file" \
  | grep -vE '^warning: `arb-engine` \(bin "arb-engine"\) generated 1 warning$')

if [ "$BUILD_RC" -ne 0 ]; then
  bad "BUILD — сборка не прошла" BUILD
  printf '%s\n' "$BUILD_LOG" | grep -E '^error' | head -20 | sed 's/^/        /'
elif [ -n "$BUILD_WARN" ]; then
  bad "BUILD — предупреждения об этом коде" BUILD
  show "$BUILD_WARN" 20
else
  ok "BUILD — чисто, ноль предупреждений об этом коде"
fi

# ---------------------------------------------------------------- TEST
# --no-fail-fast обязателен: без него первая красная корка прячет состояние
# всех остальных, и отчёт роли получается про пустоту.
TEST_LOG=$(cargo test --offline --workspace --no-fail-fast 2>&1)
TEST_RC=$?
# Считаем `passed` со всех итоговых строк, включая `FAILED`, а не только с
# `ok`. Прежний счётчик брал лишь `test result: ok.`, поэтому корка с одним
# падением обнуляла и свои зелёные тесты — счёт заваливался вниз ровно тогда,
# когда дерево красное, и TESTCOUNT врал вторым красным про удалённые тесты.
PASSED=$(printf '%s\n' "$TEST_LOG" | sed -n 's/^test result: [a-zA-Z]*\. \([0-9]*\) passed.*/\1/p' | awk '{s+=$1} END {print s+0}')
FAILED=$(printf '%s\n' "$TEST_LOG" | sed -n 's/^test result:.*; \([0-9]*\) failed.*/\1/p' | awk '{s+=$1} END {print s+0}')
IGNORED=$(printf '%s\n' "$TEST_LOG" | sed -n 's/^test result:.*; \([0-9]*\) ignored.*/\1/p' | awk '{s+=$1} END {print s+0}')

if [ "$TEST_RC" -ne 0 ] || [ "$FAILED" -ne 0 ]; then
  bad "TEST — $PASSED зелёных, $FAILED красных" TEST
  printf '%s\n' "$TEST_LOG" | grep -E "^(test .* FAILED|thread '.*' panicked)" | head -20 | sed 's/^/        /'
else
  ok "TEST — $PASSED зелёных, ноль красных"
fi
# Устав 8.5: тест не удаляют и не глушат, чтобы позеленеть. `#[ignore]` — второй
# способ сделать это, и он не виден в счёте зелёных, поэтому печатается отдельно.
if [ "$IGNORED" -ne 0 ]; then
  warn "IGNORE — $IGNORED тестов под #[ignore]; устав 8.5, назови причину каждого"
fi
echo "$PASSED" > team/.testcount.now

# ---------------------------------------------------------------- REPLAY
if cargo run --offline -q -p arb-engine -- replay fixtures/ >/dev/null 2>&1; then
  ok "REPLAY — выход 0"
else
  bad "REPLAY — ненулевой выход" REPLAY
fi

[ "${1:-}" = "fast" ] && { printf '\n%d зелёных, %d красных\n\n' "$PASS" "$FAIL"; [ "$FAIL" -eq 0 ] || exit 1; exit 0; }

# ---------------------------------------------------------------- NODEPS
# Жёсткое правило 1. Ищем секцию зависимостей, в которой есть что-то кроме
# path — то есть пакет с crates.io.
DEPS=$(grep -rn -A3 '^\[\(dev-\|build-\)\?dependencies\]' --include=Cargo.toml . 2>/dev/null \
  | grep -E '^\S+[-:][0-9]+[-:][a-zA-Z0-9_-]+ *= *' \
  | grep -v 'path *=' || true)
if [ -n "$DEPS" ]; then
  bad "NODEPS — внешняя зависимость в манифесте" NODEPS
  show "$DEPS" 10
else
  ok "NODEPS — ни одного пакета с crates.io"
fi

# ---------------------------------------------------------------- NOFLOAT
# Жёсткое правило 2 и устав раздел 6 в редакции decisions/029 п.3: область —
# **весь `crates/`, включая тесты**. Тест, сравнивающий деньги через `f64`, не
# доказывает точность, а имитирует её.
#
# Исключений по словам здесь больше нет. Прежний фильтр снимал строку, если в
# ней попадались «no f64», «not f64», «never f64» и подобное, — то есть
# позволял пронести настоящий `f64`, приписав рядом отрицание. «`f64`, который
# здесь уместен» — суждение о намерении, а греп его не выносит. Снимается
# только комментарий: текст про `f64` не есть `f64` в коде.
FLOATS=$(for f in $RS_ALL; do
    awk -v F="$f" '{
      line = $0
      sub(/[[:space:]]*\/\/.*$/, "", line)
      if (line ~ /\bf64\b|\bf32\b/) print F ":" NR ": " line
    }' "$f"
  done)
if [ -n "$FLOATS" ]; then
  bad "NOFLOAT — плавающая точка в коде" NOFLOAT
  show "$FLOATS" 10
else
  ok "NOFLOAT — ни f64, ни f32 нигде в crates/"
fi

# ---------------------------------------------------------------- NOUNWRAP
# Жёсткое правило 4: «Ошибка — значение, а не выход». Область — вне
# `#[cfg(test)]`, с гейтом в родителе (decisions/029 п.1).
UNWRAPS=$(product_lines | grep -E '\.unwrap\(\)|\.expect\(|panic!\(|unreachable!\(|todo!\(|unimplemented!\(' || true)
if [ -n "$UNWRAPS" ]; then
  bad "NOUNWRAP — паника в продуктовом коде" NOUNWRAP
  show "$UNWRAPS" 20
else
  ok "NOUNWRAP — ни unwrap, ни expect, ни panic вне тестов"
fi

# `debug_assert!` — тоже выход, а не значение: он паникует в каждой отладочной
# сборке и под `cargo test`. Но таблица гейтов раздела 6 перечисляет ровно три
# конструкции, а расширение критерия — правка устава, то есть дело LEAD, не моё
# (устав раздел 3, спор решается записью в `decisions/`). Поэтому WARN, а не
# FAIL: молчать нельзя, но и валить ночь семи ролям на неразрешённом вопросе я
# не вправе. Запрос лежит в team/inbox/LEAD.md, владелец строки — в ENG-VENUE.
DBGASSERT=$(product_lines | grep -E 'debug_assert' || true)
if [ -n "$DBGASSERT" ]; then
  warn "DEBUG_ASSERT — паника в продуктовом коде, вне таблицы гейтов; ждёт решения LEAD"
  show "$DBGASSERT" 5
fi

# ---------------------------------------------------------------- TESTCOUNT
# Тест не удаляют, чтобы позеленеть. Базлайн ставит INTEGRATOR.
if [ -f team/.testcount.baseline ]; then
  BASE=$(cat team/.testcount.baseline)
  if [ "$PASSED" -lt "$BASE" ]; then
    bad "TESTCOUNT — было $BASE зелёных, стало $PASSED" TESTCOUNT
  else
    ok "TESTCOUNT — $PASSED против базлайна $BASE"
  fi
else
  printf '  \033[33mSKIP\033[0m  TESTCOUNT — базлайна нет, ставлю: %s\n' "$PASSED"
  echo "$PASSED" > team/.testcount.baseline
fi

# ---------------------------------------------------------------- NOSECRET
# Устав раздел 8.3. Ключа в репозитории не появляется.
SECRETS=$(grep -rniE 'api[_-]?secret|api[_-]?key *= *"|X-MBX-APIKEY|hmac|signature *= *"|Bearer [A-Za-z0-9]{20}' \
  --include='*.rs' --include='*.toml' --include='*.md' crates/ 2>/dev/null \
  | grep -viE 'no (api )?key|never|forbid|there is no|not hold|no secret|absent' || true)
if [ -n "$SECRETS" ]; then
  bad "NOSECRET — похоже на ключ или подпись запроса" NOSECRET
  show "$SECRETS" 10
else
  ok "NOSECRET — ни ключа, ни подписи"
fi

# ---------------------------------------------------------------- NOTLSDOWN
# Устав раздел 8.6 и `decisions/027`. Область — вне `#[cfg(test)]`
# (decisions/029 п.2): тест, утверждающий отсутствие флага, не есть присутствие
# флага, и до этой правки гейт краснел ровно на
# `the_argument_list_never_weakens_tls` — на том самом тесте, который правило
# охраняет и на который `decisions/027` раздел 3 ссылается как на гарантию.
#
# Набор паттернов расширен той же правкой, и это не косметика. Таблица гейтов
# требует «ни `--insecure`, ни `-k`, ни `-L`, ни ослабления TLS», а скрипт не
# ловил ни `-k`, ни `-L`:
#   * `-k ` требовал пробел после флага и потому проходил мимо `"-k",` —
#     литерала в списке аргументов, то есть мимо единственной формы, в которой
#     флаг вообще может появиться в этом коде;
#   * `-L` и `--location` не имели паттерна вовсе, хотя устав называет `-L`
#     прямо;
#   * `--proxy-insecure`, `--ssl-allow-beast`, `--no-alpn` не покрывались:
#     подстроки `--insecure` в `--proxy-insecure` нет.
# Починить одну область, не починив набор, значило бы озеленить гейт, оставив
# без охраны флаги, названные уставом. Это устав раздел 9, и потому сделано
# одной правкой.
#
# Склеенная короткая форма (`-sSk`, `-kL`) ловится по букве внутри литерала, а
# не по точному совпадению: `curl -sSk` выключает проверку сертификата так же,
# как `curl -k`.
TLS=$(product_lines | grep -E -- '--insecure|--proxy-insecure|--ssl-allow-beast|--no-alpn|--ssl-no-revoke|--proto-default|--tlsv1\.[01]|--location|--cacert|--capath|danger_accept|verify[[:space:]]*=[[:space:]]*false|"-[A-Za-z]*[kL][A-Za-z]*"' || true)
if [ -n "$TLS" ]; then
  bad "NOTLSDOWN — ослабление TLS в продуктовом коде" NOTLSDOWN
  show "$TLS" 10
else
  ok "NOTLSDOWN — TLS не ослаблен"
fi

# Удаление флага греп не видит: пропавшую строку нельзя найти по образцу. А
# `--proto =https` и `--tlsv1.2` держат ровно то, что перечислено выше:
# без первого редирект уводит запрос на http, без второго допускается TLS 1.0.
# Поэтому положительная проверка — единственная, которая ловит удаление.
TLS_ARGS=crates/arb-live/src/http.rs
TLS_MISSING=""
for need in '"--proto"' '"=https"' '"--proto-redir"' '"--tlsv1.2"'; do
  grep -qF -- "$need" "$TLS_ARGS" || TLS_MISSING="$TLS_MISSING $need"
done
if [ -n "$TLS_MISSING" ]; then
  bad "NOTLSDOWN — из списка аргументов пропала защита:$TLS_MISSING" NOTLSDOWN
fi

printf '\n%d зелёных, %d красных' "$PASS" "$FAIL"
[ "$WARNS" -ne 0 ] && printf ', %d предупреждений' "$WARNS"
printf '\n'
if [ "$FAIL" -ne 0 ]; then
  printf 'КРАСНОЕ:%s\n' "$RED"
  printf 'Работа не готова. Устав раздел 6: красные гейты — стоп.\n\n'
  exit 1
fi
printf 'Все гейты зелёные.\n\n'

# ==================================================================
#  ЖУРНАЛ ПРАВОК ИЗМЕРИТЕЛЯ
# ==================================================================
# 2026-08-25 · T1a по decisions/029 · INTEGRATOR
#
# Область поиска, три гейта:
#   * NOUNWRAP и NOTLSDOWN считают модуль тестовым, если `#[cfg(test)]` стоит на
#     его объявлении `mod` в родителе. Один классификатор на оба.
#   * Тестовая область теперь закрывается по скобке на нулевой колонке, а не
#     тянется до конца файла. Это **закрывает** слепое пятно, а не открывает:
#     продуктовый код после тестового модуля прежде не проверялся вообще.
#   * NOFLOAT остался абсолютным по всему `crates/` и стал строже — сняты
#     исключения по словам, которые позволяли пронести `f64`, приписав рядом
#     отрицание.
#
# Честность измерителя:
#   * `head -10` заменён на счёт всех попаданий с печатью первых N. Прежде
#     NOUNWRAP показывал 10 из 221, и какие десять — зависело от порядка `find`.
#   * `find` отсортирован: вывод стал воспроизводимым между машинами.
#   * Счётчик TEST берёт `passed` со всех итоговых строк, а не только с `ok.`,
#     иначе счёт заваливался вниз ровно тогда, когда дерево красное.
#   * `#[ignore]` печатается отдельным WARN: устав 8.5 запрещает глушить тест,
#     а в счёте зелёных заглушенный тест не виден.
#
# Что измеритель по-прежнему НЕ ловит, названо, чтобы не выглядело охваченным:
#   * `debug_assert!` — WARN, не FAIL; расширение критерия за LEAD.
#   * Точное совпадение в `the_argument_list_never_weakens_tls`
#     (`crates/arb-live/src/http.rs:489`) пропускает склеенную короткую форму
#     `"-sSk"`. Гейт её ловит, тест — нет. Строка продуктовая, владелец
#     ENG-LIVE, сообщение у него в инбоксе.
#   * Границу модулей шеллом не проводит никто: оба допущения названы выше,
#     вместе с тем, чем каждое проверено. Появится `#[cfg(all(test, …))]`,
#     `#[path]`, блочный комментарий или `}` на нулевой колонке внутри
#     литерала — пересчитывать заново.
#   * NOSECRET сохранил исключения по словам, того же класса, что снятые в
#     NOFLOAT. Вне области T1a; отдельной задачей.
